/* The blank of an exercise: the highlighted part, or for forms/patterns the grammar ending inside it. */
export function blankOf(point,text,start,end){
 const span=[...text].slice(start,end).join('');
 const hit=[...point.choices].sort((a,b)=>b.length-a.length).find(c=>span.endsWith(c));
 if(point.group==='particle'||!hit)return {start,end,answer:span};
 const len=[...hit].length;return {start:end-len,end,answer:hit};
}
