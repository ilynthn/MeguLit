'use strict';
/* 语法 › 怎么接 (2026-11-14): furigana for MeguLit's own grammar example lines (form examples, 常见用法, 通用例句).
   Run against an installed MeguLit that has the reading pack (Sudachi tokenizer + JMdict):
     node tools/build-grammar-ruby.cjs E:/MeguLit
   The rule lives in core/grammar-ruby.cjs (dictionary readings that agree with the tokenizer, nothing else); words left
   bare are listed in the report for review. Output: web/grammar-ruby.js in Anki markup 「 漢字[かんじ]」. */
const fs=require('node:fs'),path=require('node:path'),{pathToFileURL}=require('node:url');
const {rubyLine,hasKanji}=require('../core/grammar-ruby.cjs');
const app=path.resolve(process.argv[2]||'E:/MeguLit'),repo=path.resolve(__dirname,'..');
(async()=>{
 const g=await import(pathToFileURL(path.join(repo,'web','grammar.js')).href);
 const texts=new Set();
 for(const level of ['N5','N4','N3','N2','N1','N0'])for(const p of g.pointsOf(level)){
  for(const [,b] of p.form||[])if(b)for(const part of String(b).split(/\s*[／/]\s*|\s*→\s*/))texts.add(part.replace(/[（(][^）)]*[）)]/g,'').trim());
  for(const u of p.uses||[])texts.add(u.ja);for(const b of p.builtin||[])texts.add(b.ja);
 }
 /* Japanese lines only: a form example written in Chinese (1980年代) has no kana and gets no furigana */
 const list=[...texts].filter(t=>t&&hasKanji(t)&&/[\u3040-\u30ff]/.test(t)).sort();
 const {LocalLearning}=require(path.join(app,'core','learning-native.cjs'));
 const learning=new LocalLearning(app,()=>{});
 if(!learning.installed())throw Error('reading pack not installed under '+app);
 const out={},bare=[];
 for(const text of list){const r=await rubyLine(learning,text);if(r.rb)out[text]=r.rb;for(const b of r.bare)bare.push(`${text}  ${b}`);}
 learning.stop();
 const body=`/* SPDX-License-Identifier: GPL-3.0-or-later */
/* Generated by tools/build-grammar-ruby.cjs from MeguLit's own grammar lines; readings are JMdict dictionary readings
   (EDRDG licence, see THIRD-PARTY.md) chosen in context by the Sudachi tokenizer. Do not edit by hand: rerun the tool. */
export const RUBY=${JSON.stringify(out,null,0).replace(/","/g,'",\n"')};
`;
 fs.writeFileSync(path.join(repo,'web','grammar-ruby.js'),body);
 fs.writeFileSync(path.join(process.env.REPORT_DIR||'H:/MeguLit-Work/grammar','ruby-report.txt'),`${list.length} lines, ${Object.keys(out).length} annotated\nkanji left bare:\n${bare.join('\n')}\n`);
 console.log(list.length,'lines',Object.keys(out).length,'annotated',bare.length,'bare');process.exit(0);
})().catch(e=>{console.error(e);process.exit(1);});
